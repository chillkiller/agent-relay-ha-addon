export function icon(name, size = 16) {
  const body = ICONS[name];
  if (!body) return name; // graceful: unbekannt → Text
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}
// applyIcons: [data-icon]-Platzhalter im DOM füllen (einfachstes Wiring ohne Build):
export function applyIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    el.innerHTML = icon(el.dataset.icon, el.dataset.iconSize ? Number(el.dataset.iconSize) : 16);
  });
}
